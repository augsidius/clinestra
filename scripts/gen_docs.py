TAG_TITLES = {"system": "System", "AI harness": "AI tools"}


def api():
    from clinestra import Harness
    from clinestra.server import APIKeyAuth, create_app
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        spec = create_app(Harness(packs=()), APIKeyAuth({})).openapi()
    out = [INTRO.rstrip(), "", "| Concept | Path | Create | Update | Move | Delete |", "|---|---|:-:|:-:|:-:|:-:|"]
    mark = lambda on: "yes" if on else ""
    for s in SPECS.values():
        out.append(f"| `{s.kind}` | `{s.plural}` | {mark(s.kind != 'approval')} | {mark(s.kind not in ('approval', 'proposal'))} "
                   f"| {mark(bool(s.transitions))} | {mark(s.deletable)} |")
    out += ["", EXAMPLES.rstrip(), ""]
    crud = tuple(f"{v}_{k}" for k in SPECS for v in ("list", "create", "get", "update", "transition", "delete"))
    by_tag = {}
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            if op.get("operationId") in crud:
                continue
            by_tag.setdefault((op.get("tags") or ["Other"])[0], []).append((path, method.upper(), op.get("summary", "")))
    known = [t["name"] for t in spec.get("tags", [])]
    out += ["## Other routes", "", "Routes beyond the resource pattern, by group.", ""]
    for tag in known + sorted(set(by_tag) - set(known)):
        if tag in by_tag:
            out += [f"### {TAG_TITLES.get(tag, tag)}", "", "| Method | Path | Purpose |", "|---|---|---|"]
            out += [f"| {m} | `{p}` | {s} |" for p, m, s in by_tag[tag]] + [""]
    (DOCS / "api.md").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    api()
    print("Wrote docs/api.md")
