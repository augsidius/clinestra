"""Regenerate docs/api.md from the code. concepts() and definitions() write the open specification sources. Run: python scripts/gen_docs.py"""
import warnings
from pathlib import Path

from clinestra.concepts.common import SYSTEM_FIELDS
from clinestra.concepts.definitions import DEF_CONFIGS, DEF_INSTANCE_KIND
from clinestra.spec import SPECS

DOCS = Path(__file__).resolve().parent.parent / "docs"


def _type(f):
    s = str(f.annotation).replace("typing.", "").replace("<class '", "").replace("'>", "")
    for junk in ("clinestra.concepts.", "people.", "clinical.", "care.", "capture.", "governance.", "common.",
                 "definitions.", "datetime.", "Optional[", "NoneType"):
        s = s.replace(junk, "")
    return s.rstrip("]") if "Optional[" in str(f.annotation) else s


def _desc(f):
    return (f.description or "").replace("|", "/")


def concepts():
    out = ["# Concepts", "",
           "Generated from `clinestra/spec.py` by `scripts/gen_docs.py`. Every record also carries `id`, `site`, "
           "`status`, `created_at`, `created_by`, `updated_at`, `updated_by`, `deleted`, and, when made from a template, "
           "`definition_key`, `definition_id` and `definition_version`.", "",
           "**Clinical** means only a clinician may make that change; automatic reactions and AI agents can only "
           "*propose* it. **Frozen** states refuse edits and deletes. **Gated** states need an approval from someone "
           "other than the requester.", ""]
    group = None
    for s in SPECS.values():
        if s.group != group:
            group = s.group
            out += [f"## {group}", ""]
        out += [f"### {s.kind}", "", s.model.__doc__.strip(), ""]
        moves = "; ".join(f"`{a}` → {', '.join(f'`{b}`' for b in bs)}" for a, bs in s.transitions.items()) or "decided via its own endpoint"
        clinical = "yes" if s.clinical is True else ("for orders, referrals and medications" if callable(s.clinical) else "no")
        rows = [("API", f"`/v1/{s.plural}`"), ("States", ", ".join(f"`{x}`" for x in s.states) + f" (starts `{s.initial}`)"),
                ("Moves", moves), ("Clinical", clinical + (f"; entering {', '.join(sorted(s.clinical_to))} is clinical" if s.clinical_to else "")),
                ("Frozen", ", ".join(sorted(s.frozen_states)) or "none"), ("Gated", ", ".join(sorted(s.approval_states)) or "none"),
                ("Written by", ", ".join(sorted(s.write_roles)) or "the harness only"
                 + (" (patients may create)" if s.patient_can_create else "")),
                ("AI agents", "may create drafts" if s.agent_can_create else "propose only"),
                ("Template", f"`{s.definition_kind}` definitions" if s.definition_kind else "none"),
                ("Deletable", "soft delete" if s.deletable else "never; use a closing/error state")]
        if s.patient_can_create and s.write_roles:
            rows[6] = ("Written by", ", ".join(sorted(s.write_roles)) + "; patients may create their own")
        out += ["| | |", "|---|---|"] + [f"| {a} | {b} |" for a, b in rows] + [""]
        out += ["| Field | Type | Notes |", "|---|---|---|"]
        for name, f in s.model.model_fields.items():
            if name in SYSTEM_FIELDS or name == "definition_key":
                continue
            req = "**required** " if f.is_required() else ""
            ro = "set by the harness. " if name in s.readonly else ""
            out.append(f"| `{name}` | `{_type(f)}` | {req}{ro}{_desc(f)} |")
        out.append("")
    (DOCS / "concepts.md").write_text("\n".join(out))


def definitions():
    out = ["# Definitions (templates)", "",
           "Generated by `scripts/gen_docs.py`. A definition is a versioned, configurable template. Create one with "
           "`POST /v1/definitions` (`def_kind`, `key`, `name`, `config`), publish it with a transition to `published`, then "
           "create instances with `definition_key`. Published definitions are frozen; a new draft with the same key gets "
           "the next version. Pack definitions are shared across sites and read-only.", "",
           "Every config also accepts `defaults` (fields copied into new instances) and `approval_required_for` "
           "(extra gated states).", ""]
    for k, cfg in DEF_CONFIGS.items():
        target = DEF_INSTANCE_KIND[k]
        out += [f"## {k}", "", f"Templates: `{target}`." if target else "Used by the harness itself.", ""]
        fields = {n: f for n, f in cfg.model_fields.items() if n not in ("defaults", "approval_required_for")}
        if fields:
            out += ["| Field | Type | Notes |", "|---|---|---|"]
            for n, f in fields.items():
                out.append(f"| `{n}` | `{_type(f)}` | {'**required** ' if f.is_required() else ''}{_desc(f)} |")
            out.append("")
    (DOCS / "definitions.md").write_text("\n".join(out))


INTRO = """# HTTP API

The live reference is at `/docs` on a running server, and the OpenAPI schema is at `/openapi.json`. This page is generated by `scripts/gen_docs.py`.

## Basics

**Base URL:** `http://127.0.0.1:8000/v1` by default. All bodies are JSON.

**Authentication:** send your key on every request, except `GET /v1/health`.

```
Authorization: Bearer <key>
```

Create keys with `clinestra keys create`. Your key decides who you are, your role and your site, so these never go in a request body.

## Status codes

| Code | Meaning |
|---|---|
| 200 | Done |
| 201 | Created |
| 202 | The state needs approval. The response is an approval to decide. |
| 401 | The key is missing or unknown |
| 403 | Your role may not do this |
| 404 | Not found, or in another site |
| 409 | A clinical or state rule refused it |
| 422 | The input is invalid |

Rule errors look like this:

```json
{"error": "InvariantViolation", "detail": "careplan cannot move from 'active' to 'nonsense'. Allowed: ['completed', 'cancelled']", "request_id": "325dcde3f536"}
```

A malformed body returns the framework's form, `{"detail": [{"loc": ["body", "country"], "msg": "Field required", ...}]}`. A missing key returns `{"detail": "Missing or unknown API key"}`.

## Listing

Every concept's list route takes these optional query parameters:

| Parameter | Effect |
|---|---|
| `patient_id` | Records for one patient |
| `status` | Records in one state |
| `encounter_id` | Records for one encounter, where the concept has that field |
| `definition_key` | Records made from one template |
| `include_deleted` | Include soft-deleted records |
| `limit` | Page size, 1 to 1000 |
| `cursor` | The `next_cursor` of the previous page |

Without `limit` the response is a plain array. With `limit` it is `{"items": [...], "next_cursor": "..."}`, and `next_cursor` is `null` on the last page.

## Resource pattern

Every concept follows one pattern. Replace `{path}` with the path in the table below.

| Verb | Route | Purpose |
|---|---|---|
| List | `GET /v1/{path}` | List records |
| Create | `POST /v1/{path}` | Create a record |
| Read | `GET /v1/{path}/{id}` | Read one record |
| Update | `PATCH /v1/{path}/{id}` | Change fields |
| Move | `POST /v1/{path}/{id}/transition` | Change state: `{"to": "...", "reason": "..."}` |
| Delete | `DELETE /v1/{path}/{id}?reason=...` | Soft delete; the reason needs at least 3 characters |

List and Read exist for every concept. The table shows the others. To see states and fields, run `clinestra concepts NAME`.

"""

